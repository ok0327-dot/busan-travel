class UpsertRefresh(unittest.TestCase):
    """다시 수집된 블로그 글(같은 source+source_id)은 새 날짜·카테고리로 덮인다.
    / A re-collected row gets the new start/end/category; COALESCE-kept enrich fields survive."""

    def test_recollected_blog_row_gets_event_dates(self):
        with tempfile.TemporaryDirectory() as d:
            conn = connect(Path(d) / "t.db")
            old = Event(source="naver_blog:bsjunggu", source_id="1", title="백산어린이 연극한마당",
                        category="blog_post", start_date="2026-10-26", lat=35.1, lon=129.03)
            self.assertEqual(upsert_events(conn, [old]), (1, 0))
            new = Event(source="naver_blog:bsjunggu", source_id="1", title="백산어린이 연극한마당",
                        category="festival", start_date="2026-10-31", end_date="2026-10-31")
            self.assertEqual(upsert_events(conn, [new]), (0, 1))
            row = conn.execute("SELECT category, start_date, end_date, lat FROM events").fetchone()
            conn.close()
        self.assertEqual(tuple(row), ("festival", "2026-10-31", "2026-10-31", 35.1))


