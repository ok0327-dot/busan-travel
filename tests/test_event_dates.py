class YearInference(unittest.TestCase):
    """연도 없는 날짜 → 게시일 기준 추정 (합성 문장 / synthetic one-liners)."""

    def test_december_post_january_event_rolls_over(self):
        p = extract_event_period("신년 음악회", "✅ 일시: 1. 2.(토) 15:00", "2026-12-20")  # 2027-01-02 토
        self.assertEqual(p, EventPeriod("2027-01-02", "2027-01-02", "label"))
        p = extract_event_period("신년 음악회", "✅ 일시: 1월 2일 15:00", "2026-12-20")      # 요일 없이도
        self.assertEqual(p, EventPeriod("2027-01-02", "2027-01-02", "label"))

    def test_range_across_new_year(self):
        p = extract_event_period("겨울 축제", "✅ 기간: 12. 26.(토) ~ 1. 4.(월)", "2026-12-01")
        self.assertEqual(p, EventPeriod("2026-12-26", "2027-01-04", "label"))

    def test_weekday_picks_the_year(self):
        # 2026-01-03 은 토요일, 2027-01-03 은 일요일 → '(토)' 면 2026 (게시일보다 과거라 None)
        self.assertIsNone(extract_event_period("x", "일시: 1. 3.(토)", "2026-01-10"))
        p = extract_event_period("x", "일시: 1. 3.(일)", "2026-12-28")
        self.assertEqual(p, EventPeriod("2027-01-03", "2027-01-03", "label"))

    def test_past_cue_keeps_previous_year_side(self):
        self.assertIsNone(extract_event_period("후기", "지난 8월 11일 열린 행사", "2026-10-28"))

    def test_two_digit_year(self):
        p = extract_event_period("x", "일시: '26. 11. 21.(토)", "2026-11-01")
        self.assertEqual(p, EventPeriod("2026-11-21", "2026-11-21", "label"))

    def test_iso_and_korean_full_dates(self):
        self.assertEqual(extract_event_period("x", "일시: 2026-11-21", "2026-11-01").start, "2026-11-21")
        self.assertEqual(extract_event_period("x", "일시: 2026년 11월 21일(토)", "2026-11-01").start, "2026-11-21")

    def test_post_date_required(self):
        self.assertIsNone(extract_event_period("x", "일시: 2026. 11. 21.(토)", None))
        self.assertIsNone(extract_event_period("x", "일시: 2026. 11. 21.(토)", "not-a-date"))

    def test_too_long_or_too_far(self):
        self.assertIsNone(extract_event_period("x", "기간: 2026. 1. 1. ~ 12. 31.", "2026-01-01"))  # 1년짜리
        self.assertIsNone(extract_event_period("x", "일시: 2027. 12. 1.", "2026-01-01"))          # 너무 먼 미래


